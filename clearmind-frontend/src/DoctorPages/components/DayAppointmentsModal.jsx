/* ─────────────────────────────────────────────────────────
   Safe date / time helpers
───────────────────────────────────────────────────────── */
function safeFormatDate(value, fmt = "MMMM d, yyyy") {
  if (!value) return "—";
  try {
    if (value instanceof Date)
      return isNaN(value.getTime()) ? "—" : format(value, fmt);
    // Handle ISO strings like "2005-09-21T00:00:00.000000Z"
    if (typeof value === "string") {
      // Plain date string YYYY-MM-DD
      if (/^\d{4}-\d{2}-\d{2}$/.test(value))
        return format(new Date(value + "T00:00:00"), fmt);
      // ISO datetime string — parse and format
      const d = new Date(value);
      return isNaN(d.getTime()) ? "—" : format(d, fmt);
    }
    const d = new Date(value);
    return isNaN(d.getTime()) ? "—" : format(d, fmt);
  } catch {
    return "—";
  }
}

function safeTime12(value) {
  if (!value) return "—";
  if (typeof value === "string" && /^\d{1,2}:\d{2}/.test(value))
    return toTime12(value);
  if (value instanceof Date && !isNaN(value.getTime())) {
    const h = value.getHours(),
      m = String(value.getMinutes()).padStart(2, "0");
    return `${h % 12 || 12}:${m} ${h >= 12 ? "PM" : "AM"}`;
  }
  return "—";
}

function normalizeAppt(appt) {
  if (!appt) return appt;
  if (appt.appointmentDate && appt.startTime) return appt;

  const start =
    appt.start instanceof Date
      ? appt.start
      : appt.start
        ? new Date(appt.start)
        : null;
  const end =
    appt.end instanceof Date ? appt.end : appt.end ? new Date(appt.end) : null;
  const padT = (d) =>
    d
      ? `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`
      : null;

  return {
    ...appt,
    appointmentDate: start
      ? `${start.getFullYear()}-${String(start.getMonth() + 1).padStart(2, "0")}-${String(start.getDate()).padStart(2, "0")}`
      : appt.appointmentDate || null,
    startTime: appt.startTime || padT(start),
    endTime: appt.endTime || padT(end),
    visitType:
      appt.visitType ||
      (appt.title?.toLowerCase().includes("online") ? "virtual" : "onsite"),
    serviceType: appt.serviceType || "",
    patientName:
      appt.patientName ||
      [appt.patient?.firstName, appt.patient?.lastName]
        .filter(Boolean)
        .join(" ") ||
      "—",
    status: appt.status || "pending",
    paymentStatus: appt.paymentStatus || appt.payment_status || "not_paid",
    paymentReference: appt.paymentReference || appt.payment_reference || null,
    assessmentPurpose:
      appt.assessmentPurpose || appt.pae_purpose || appt.paePurpose || null,
    reason: appt.reason || appt.reason_for_consultation || null,
    receiptPaths: appt.receiptPaths || appt.receipt_paths || [],
    appointment_id: appt.appointment_id || appt.id,
    appointmentRef: appt.appointmentRef || appt.appointment_ref || "—",
  };
}

