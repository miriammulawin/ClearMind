/* ─────────────────────────────────────────────────────────
   MAIN COMPONENT
───────────────────────────────────────────────────────── */
function DayAppointmentsModal({ isOpen, onClose, selectedDate }) {
  const [appointments, setAppointments] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [activeAppt, setActiveAppt] = useState(null);

  const loadAppointments = useCallback(async (date, signal) => {
    if (!date) return;
    setLoading(true);
    setError(null);
    try {
      const raw = await fetchAppointments(date, signal);
      setAppointments(raw.map(mapAppointment));
    } catch (e) {
      if (e.name !== "AbortError")
        setError(e.message || "Failed to load appointments.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    if (!isOpen || !selectedDate) return;
    setActiveAppt(null);
    const ctrl = new AbortController();
    loadAppointments(new Date(selectedDate), ctrl.signal);
    return () => ctrl.abort();
  }, [isOpen, selectedDate, loadAppointments]);

  if (!isOpen || !selectedDate) return null;

  const dateObj = new Date(selectedDate);
  const formattedDate = format(dateObj, "MMMM d, yyyy");
  const dayName = format(dateObj, "EEEE");
  const handleRefresh = () => loadAppointments(dateObj);

  if (activeAppt) {
    return (
      <DetailView
        appt={activeAppt}
        onClose={onClose}
        onBack={() => setActiveAppt(null)}
        onRefresh={() => {
          setActiveAppt(null);
          handleRefresh();
        }}
      />
    );
  }

  return (
    <div className={styles.overlay} onClick={onClose}>
      <div className={styles.modal} onClick={(e) => e.stopPropagation()}>
        <div className={styles.modalHeader}>
          <h3 className={styles.modalTitle}>{dayName}'s Appointments</h3>
          <div className={styles.modalHeaderRight}>
            <span className={styles.dateBadge}>{formattedDate}</span>
            <button
              onClick={handleRefresh}
              disabled={loading}
              title="Refresh"
              style={{
                background: "none",
                border: "1px solid #e2d5f5",
                borderRadius: "7px",
                cursor: "pointer",
                color: "#ffffff",
                padding: "5px",
                display: "flex",
                alignItems: "center",
                opacity: loading ? 0.5 : 1,
              }}
            >
              <FiRefreshCw
                size={14}
                style={{
                  animation: loading ? "spin 1s linear infinite" : "none",
                }}
              />
            </button>
            <button
              className={styles.closeBtn}
              onClick={onClose}
              aria-label="Close"
            >
              <FiX />
            </button>
          </div>
        </div>

        <div className={styles.scrollBody}>
          {loading ? (
            <LoadingSkeleton />
          ) : error ? (
            <div style={{ textAlign: "center", padding: "40px 20px" }}>
              <div style={{ fontSize: "32px", marginBottom: "12px" }}>⚠️</div>
              <p
                style={{
                  color: "#dc2626",
                  fontSize: "14px",
                  margin: "0 0 16px",
                  fontFamily: "'Poppins',sans-serif",
                }}
              >
                {error}
              </p>
              <button
                onClick={handleRefresh}
                style={{
                  background: "#4D227C",
                  color: "#fff",
                  border: "none",
                  borderRadius: "8px",
                  padding: "8px 20px",
                  cursor: "pointer",
                  fontSize: "13px",
                  fontWeight: "600",
                  display: "inline-flex",
                  alignItems: "center",
                  gap: "6px",
                }}
              >
                <FiRefreshCw size={13} /> Try Again
              </button>
            </div>
          ) : appointments.length === 0 ? (
            <div
              style={{
                textAlign: "center",
                color: "#9ca3af",
                fontSize: 14,
                padding: "48px 0",
                fontFamily: "'Poppins',sans-serif",
              }}
            >
              <div style={{ fontSize: 40, marginBottom: 12, opacity: 0.3 }}>
                📅
              </div>
              <p style={{ margin: 0 }}>
                No appointments scheduled for this day.
              </p>
            </div>
          ) : (
            <>
              <div
                style={{
                  fontSize: "12px",
                  color: "#9c7dd4",
                  fontWeight: "600",
                  marginBottom: "12px",
                  fontFamily: "'Poppins',sans-serif",
                }}
              >
                {appointments.length} appointment
                {appointments.length !== 1 ? "s" : ""} on {formattedDate}
              </div>
              {appointments.map((appt) => (
                <AppointmentCard
                  key={appt.id}
                  appt={appt}
                  onView={setActiveAppt}
                />
              ))}
            </>
          )}
        </div>
      </div>
      <style>{`@keyframes spin{from{transform:rotate(0deg)}to{transform:rotate(360deg)}}`}</style>
    </div>
  );
}

export default DayAppointmentsModal;
